"""Review a completed Stage logic run; never starts Vivado or touches a device."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
import uuid

from prepare_system import digest, relative_file, require
from verify_system import check_hwh, check_ps, check_logic_evidence, check_simulation_steps
from model_patch import SOURCE_SHA, PARAMS_SHA, PARAMS

ROOT = Path(__file__).resolve().parents[1]


def verify(root, run):
    root, run = root.resolve(strict=True), run.resolve(strict=True)
    require(run.parent == root / "build", "run must be a direct child of this project build directory")
    receipt_path = run / "logic_verified.json"
    require(not receipt_path.exists(), "preserve the existing simulation receipt")
    recipe_raw = (root / "project_manifest.json").read_bytes()
    recipe = json.loads(recipe_raw)
    require(recipe["schema"] == "opt50_system_recipe_v1" and recipe["status"] == "PREPARED_NOT_RUN" and
            recipe["simulation_model"] == "LOCAL_ARB_FIXED_V1" and recipe["real_case_profile"] == "full48",
            "wrong frozen system simulation recipe")
    for name, expected in recipe["files"].items():
        file = relative_file(root, name)
        require(file.stat().st_size == expected["bytes"] and digest(file) == expected["sha256"],
                "frozen source changed: " + name)
    identity = json.loads((run / "run_manifest.json").read_text(encoding="utf-8-sig"))
    require(identity["schema"] == "opt50_system_run_v1" and identity["stage"] == "logic" and
            identity["tool_version"] == "2026.1" and identity["run_id"] == run.name and
            identity["recipe_sha256"] == hashlib.sha256(recipe_raw).hexdigest() and
            identity["clock_hz"] == 125000000, "not this recipe's Stage logic run")
    fingerprint = hashlib.sha256((identity["recipe_sha256"] + "|" + run.name + "|2026.1").encode()).hexdigest()
    require(identity["build_fingerprint"] == fingerprint and
            identity["observer_tags"] == [int(fingerprint[:8], 16), int(fingerprint[8:16], 16)] and
            identity["metadata_uuid"] == str(uuid.UUID(fingerprint[:32])), "run identity chain differs")
    for name in ("bd_pass.txt", "board_logic_pass.txt"):
        require((run / name).read_text().strip() == "PASS", "missing actual stage marker: " + name)
    require(not any((run / name).exists() for name in ("failure.txt", "build_pass.txt", "artifacts")),
            "failed run or unexpected implementation artifacts")
    console = (run / "vivado_console.log").read_text(errors="replace")
    require(not re.search(r"Launched (?:synth_1|impl_1)|OPT50_SYSTEM_STAGE_FAIL", console),
            "simulation-only run launched implementation or failed")
    proof = check_logic_evidence(
        (run / "board_logic_simulate.log").read_text(errors="replace"), identity["observer_tags"],
        (run / "board_logic_elaborate.bat").read_text(errors="replace"),
        (run / "simulation_model_scope.txt").read_text(errors="replace"))
    steps = check_simulation_steps(run)
    # Resolve the unique handoff generated by this actual production BD, not a
    # copied previous build's HWH or a fabricated simplified system.
    candidates = [run / f"project/opt50_kv260.{folder}/sources_1/bd/kv260_opt50/hw_handoff/kv260_opt50.hwh"
                  for folder in ("gen", "srcs")]
    handoffs = [p for p in candidates if p.is_file()]
    require(len(handoffs) == 1, "unique current generated production HWH required")
    abi = json.loads((root / "input/opt50_abi.json").read_bytes())
    hwh = check_hwh(handoffs[0].read_bytes(), abi, identity["observer_tags"])
    ddr_count = check_ps((run / "ps_properties.txt").read_text(errors="replace"),
                         (root / "input/board_files/kv260/1.1/preset_s4.xml").read_bytes())
    patch = json.loads((root / "input/sim_model/patch_manifest.json").read_bytes())
    vendor = Path(patch["original_vendor_source"])
    require(patch["original_source_sha256"] == SOURCE_SHA and digest(vendor) == SOURCE_SHA and
            digest(vendor.parent / PARAMS) == PARAMS_SHA, "AMD installed source identity changed")
    cases = json.loads((root / "input/sim_cases/real_cases_manifest.json").read_bytes())
    require(cases["job_count"] == 48 and cases["INT32_outputs"] == 1870848 and
            cases["package_manifest_sha256"] == "6d34397bae245400f19f674e98eb5726896aaa2a3e2545adf656254527585fcf",
            "wrong real-case package")
    simdir = run / "project/opt50_kv260.sim/sim_1/behav/xsim"
    simulator_files = ("xsim.ini", "xvlog.log", "local_model_compile.log", "elaborate.log", "simulate.log",
                       "xsim.dir/opt50_ps_vip_fixed/opt50_ps_vip_fixed.rlx",
                       "xsim.dir/opt50_ps_vip_fixed/zynq_ultra_ps_e_vip_v1_0_23_arb_wr_6.sdb")
    simulator_evidence = {}
    for name in simulator_files:
        file = relative_file(simdir, name)
        require(file.stat().st_size > 0, "empty actual simulator evidence: " + name)
        simulator_evidence[name] = dict(bytes=file.stat().st_size, sha256=digest(file))
    evidence_names = ("run_manifest.json", "stage_scope.txt", "bd_pass.txt", "board_logic_pass.txt",
                      "board_logic_simulate.log", "board_logic_elaborate.bat", "simulation_model_scope.txt",
                      "vivado_console.log", "reset_contract.txt", "reset_properties.txt", "ps_properties.txt",
                      "board_logic_elaborate_original.bat", "board_logic_step_compile.log",
                      "board_logic_step_local_model.log", "board_logic_step_elaborate.log", "board_logic_step_simulate.log")
    receipt = dict(schema="opt50_system_logic_verified_v1", status="PASS_SYSTEM_RTL_WITH_LOCAL_MODEL",
                   run_id=run.name, recipe_sha256=identity["recipe_sha256"], observer_tags=identity["observer_tags"],
                   proof=proof, steps=steps, hwh=dict(path=handoffs[0].relative_to(run).as_posix(), sha256=digest(handoffs[0])),
                   static_hwh=hwh, DDR_parameters_checked=ddr_count, files_checked=len(recipe["files"]),
                   installed_vendor_sources_unchanged=True,
                   actual_simulator_files=simulator_evidence,
                   evidence={name: dict(bytes=(run/name).stat().st_size, sha256=digest(run/name)) for name in evidence_names},
                   simulation_model="PROJECT_LOCAL_ARB_FIXED_V1_NOT_AMD_ISSUED_FIX",
                   original_vendor_model="HISTORICAL_FAIL_PRESERVED_SEPARATE_ARCHIVE_NOT_REVERIFIED_HERE",
                   physical_PL_starts=0, synthesis="NOT_RUN", implementation="NOT_RUN", board="NOT_RUN",
                   scope="Actual production BD RTL simulation using local PS VIP arbiter workaround; NOT board or accuracy acceptance")
    with receipt_path.open("x", encoding="utf-8") as handle:
        handle.write(json.dumps(receipt, indent=2) + "\n")
    return receipt


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, required=True)
    args = parser.parse_args()
    try:
        print(json.dumps(verify(ROOT, args.run), indent=2))
    except (ValueError, KeyError, OSError) as error:
        raise SystemExit("REFUSED: " + str(error))
