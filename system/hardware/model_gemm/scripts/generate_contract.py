"""Generate one shared HLS/host shape table from the ABI capability source."""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]


def render(cap):
    rows = ",\n".join('    {"%s", %d, %d, %d}' % (s["family"], s["M"], s["K"], s["N"]) for s in cap["shapes"])
    tm, tn, tk = (cap["tile"][k] for k in ("TM", "TN", "TK"))
    mx, mw, my = (cap["max_elements"][k] for k in ("X", "W", "Y"))
    return '''// Generated by scripts/generate_contract.py. Edit contracts/capabilities.json.
#ifndef MODEL_GEMM_CONFIG_HPP
#define MODEL_GEMM_CONFIG_HPP
#include <stdint.h>
namespace model_gemm {
typedef int8_t input_t;
typedef int16_t product_t;
typedef int32_t output_t;
static_assert(sizeof(input_t)==1 && sizeof(product_t)==2 && sizeof(output_t)==4, "ABI types");
static const unsigned TM=%d, TN=%d, TK=%d;
static const unsigned MICRO_M=8, MICRO_N=8;
static const unsigned MAX_X=%d, MAX_W=%d, MAX_Y=%d;
enum Error { OK=0, INVALID_SHAPE=1 };
struct Shape { const char* family; uint32_t M, K, N; };
static const Shape SHAPES[5] = {
%s
};
inline bool valid_shape(uint32_t M, uint32_t K, uint32_t N) {
    return %s;
}
}
uint32_t model_gemm_top(const model_gemm::input_t* X, const model_gemm::input_t* W,
                       model_gemm::output_t* Y, uint32_t M, uint32_t K, uint32_t N);
#endif
''' % (tm, tn, tk, mx, mw, my, rows, " ||\n           ".join("(M==%du && K==%du && N==%du)" % (s["M"], s["K"], s["N"]) for s in cap["shapes"]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    cap = json.loads((ROOT / "contracts/capabilities.json").read_text(encoding="utf-8"))
    assert len(cap["shapes"]) == 5 and len({(s["M"], s["K"], s["N"]) for s in cap["shapes"]}) == 5
    assert cap["tile"] == {"TM":8, "TN":64, "TK":32, "micro_rows":8, "micro_cols":8, "buffers":1}
    for name, field in (("X", lambda s:s["M"]*s["K"]), ("W", lambda s:s["K"]*s["N"]), ("Y", lambda s:s["M"]*s["N"])):
        assert cap["max_elements"][name] == max(field(s) for s in cap["shapes"])
    target = ROOT / "include/model_gemm_config.hpp"
    text = render(cap)
    if args.check:
        assert target.read_text(encoding="utf-8") == text, "Generated header stale"
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
    print("CONTRACT_HEADER_PASS", target)


if __name__ == "__main__":
    main()
